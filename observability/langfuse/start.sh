#!/usr/bin/env bash
# Create .env on first run, then start the local Langfuse stack.
#   bash observability/langfuse/start.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=common.sh
source "${ROOT}/common.sh"

require_docker

volume_exists() {
  docker volume ls -q | grep -qx 'skills-langfuse_postgres-data'
}

write_env() {
  local postgres_password clickhouse_password redis_auth minio_password
  local nextauth_secret salt encryption_key public_key secret_key user_password
  postgres_password="$(openssl rand -hex 24)"
  clickhouse_password="$(openssl rand -hex 24)"
  redis_auth="$(openssl rand -hex 24)"
  minio_password="$(openssl rand -hex 24)"
  nextauth_secret="$(openssl rand -hex 32)"
  salt="$(openssl rand -hex 16)"
  encryption_key="$(openssl rand -hex 32)"
  public_key="pk-lf-$(openssl rand -hex 16)"
  secret_key="sk-lf-$(openssl rand -hex 32)"
  user_password="$(openssl rand -hex 12)"

  umask 077
  cat >"$ENV_FILE" <<EOF
# Generated by start.sh. Do not commit.
NEXTAUTH_URL=http://localhost:3100
LANGFUSE_S3_MEDIA_UPLOAD_ENDPOINT=http://localhost:9190
TELEMETRY_ENABLED=false

LANGFUSE_WEB_PORT=3100
LANGFUSE_WORKER_PORT=3130
LANGFUSE_POSTGRES_PORT=5433
LANGFUSE_REDIS_PORT=6381
LANGFUSE_CLICKHOUSE_HTTP_PORT=8124
LANGFUSE_CLICKHOUSE_NATIVE_PORT=9001
LANGFUSE_MINIO_PORT=9190
LANGFUSE_MINIO_CONSOLE_PORT=9191

POSTGRES_PASSWORD=${postgres_password}
CLICKHOUSE_PASSWORD=${clickhouse_password}
REDIS_AUTH=${redis_auth}
MINIO_ROOT_PASSWORD=${minio_password}
NEXTAUTH_SECRET=${nextauth_secret}
SALT=${salt}
ENCRYPTION_KEY=${encryption_key}

LANGFUSE_INIT_ORG_ID=local
LANGFUSE_INIT_ORG_NAME=Local
LANGFUSE_INIT_PROJECT_ID=local
LANGFUSE_INIT_PROJECT_NAME=Local
LANGFUSE_INIT_PROJECT_PUBLIC_KEY=${public_key}
LANGFUSE_INIT_PROJECT_SECRET_KEY=${secret_key}
LANGFUSE_INIT_USER_EMAIL=admin@langfuse.local
LANGFUSE_INIT_USER_NAME=Local
LANGFUSE_INIT_USER_PASSWORD=${user_password}
EOF
}

require_env() {
  local key="$1"
  local value
  value="$(env_value "$key")"
  if [[ -z "$value" || "$value" == "CHANGEME" || "$value" == *-CHANGEME ]]; then
    echo "${key} is missing in ${ENV_FILE}." >&2
    exit 1
  fi
}

if ! command -v openssl >/dev/null 2>&1; then
  echo "openssl is required." >&2
  exit 1
fi
if ! command -v curl >/dev/null 2>&1; then
  echo "curl is required." >&2
  exit 1
fi

if [[ ! -f "$ENV_FILE" ]]; then
  if volume_exists; then
    echo "Missing ${ENV_FILE}, but Langfuse data volumes already exist." >&2
    echo "Restore that file, or wipe the volumes with:" >&2
    echo "  bash observability/langfuse/cleanup.sh" >&2
    exit 1
  fi
  echo "==> Writing ${ENV_FILE}"
  write_env
fi

require_env POSTGRES_PASSWORD
require_env CLICKHOUSE_PASSWORD
require_env REDIS_AUTH
require_env MINIO_ROOT_PASSWORD
require_env NEXTAUTH_SECRET
require_env SALT
require_env ENCRYPTION_KEY
require_env LANGFUSE_INIT_USER_EMAIL
require_env LANGFUSE_INIT_USER_PASSWORD
require_env LANGFUSE_INIT_PROJECT_PUBLIC_KEY
require_env LANGFUSE_INIT_PROJECT_SECRET_KEY

encryption_key="$(env_value ENCRYPTION_KEY)"
if [[ ! "$encryption_key" =~ ^[0-9a-fA-F]{64}$ ]]; then
  echo "ENCRYPTION_KEY in ${ENV_FILE} must be 64 hex characters (openssl rand -hex 32)." >&2
  exit 1
fi

web_port="$(env_value LANGFUSE_WEB_PORT)"
minio_port="$(env_value LANGFUSE_MINIO_PORT)"
minio_console_port="$(env_value LANGFUSE_MINIO_CONSOLE_PORT)"

running="$(compose ps --status running -q || true)"
if [[ -z "$running" ]]; then
  busy=()
  for port in \
    "$web_port" \
    "$(env_value LANGFUSE_WORKER_PORT)" \
    "$(env_value LANGFUSE_POSTGRES_PORT)" \
    "$(env_value LANGFUSE_REDIS_PORT)" \
    "$(env_value LANGFUSE_CLICKHOUSE_HTTP_PORT)" \
    "$(env_value LANGFUSE_CLICKHOUSE_NATIVE_PORT)" \
    "$minio_port" \
    "$minio_console_port"
  do
    if [[ -z "$port" ]]; then
      echo "A LANGFUSE_*_PORT value is missing in ${ENV_FILE}." >&2
      exit 1
    fi
    if lsof -nP -iTCP:"${port}" -sTCP:LISTEN >/dev/null 2>&1; then
      busy+=("$port")
    fi
  done
  if ((${#busy[@]})); then
    echo "These ports are already in use: ${busy[*]}" >&2
    echo "Change the LANGFUSE_*_PORT values in ${ENV_FILE}, and keep NEXTAUTH_URL and LANGFUSE_S3_MEDIA_UPLOAD_ENDPOINT pointed at the UI and MinIO ports." >&2
    exit 1
  fi
fi

echo "==> Starting Langfuse"
if ! compose up -d --wait --wait-timeout 300; then
  echo "Langfuse containers did not become healthy." >&2
  compose ps >&2 || true
  compose logs --tail=60 langfuse-web langfuse-worker postgres clickhouse redis minio >&2 || true
  exit 1
fi

echo "==> Waiting for the UI"
ready=0
for _ in $(seq 1 90); do
  code="$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:${web_port}/api/public/health" || true)"
  if [[ "$code" == "200" ]]; then
    ready=1
    break
  fi
  sleep 2
done

if [[ "$ready" -ne 1 ]]; then
  echo "Langfuse did not become ready. Recent web logs:" >&2
  compose logs --tail=80 langfuse-web >&2 || true
  exit 1
fi

echo ""
echo "Langfuse is up: http://localhost:${web_port}"
echo "Email: $(env_value LANGFUSE_INIT_USER_EMAIL)"
echo "Password: $(env_value LANGFUSE_INIT_USER_PASSWORD)"
echo "Public key: $(env_value LANGFUSE_INIT_PROJECT_PUBLIC_KEY)"
echo "Secret key: $(env_value LANGFUSE_INIT_PROJECT_SECRET_KEY)"
echo "MinIO API: http://localhost:${minio_port}"
echo "MinIO console: http://localhost:${minio_console_port}  (user minio, password in ${ENV_FILE})"
echo "Credentials file: ${ENV_FILE}"
echo "Stop it with:"
echo "  bash observability/langfuse/stop.sh"
